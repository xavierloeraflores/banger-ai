/* eslint-disable @typescript-eslint/no-require-imports -- Electron exposes its runtime module through require in this standalone smoke script. */
// Run with Electron against a local API and a dedicated test database.
const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const { writeFile } = require('node:fs/promises');
const origin = process.env.BANGER_SMOKE_URL || 'http://127.0.0.1:3048';
if (!['localhost', '127.0.0.1'].includes(new URL(origin).hostname)) throw new Error('Account smoke tests require a local test server.');
const username = `smoke_${Date.now()}`;
const password = 'local-fixture-password-123';
const timer = setTimeout(() => { console.error('Account smoke timed out'); app.exit(1); }, 90000);
app.whenReady().then(async () => {
  const window = new BrowserWindow({ width: 1440, height: 1000, show: false, webPreferences: { partition: `account-smoke-${Date.now()}`, sandbox: true, contextIsolation: true, nodeIntegration: false, backgroundThrottling: false } });
  const errors = [];
  window.webContents.on('console-message', event => { if (event.level === 'error' && !event.message.includes('Failed to load resource')) errors.push(event.message); });
  const evaluate = code => window.webContents.executeJavaScript(code, true);
  const wait = async condition => {
    for (let i = 0; i < 100; i++) { if (await evaluate(condition)) return; await new Promise(resolve => setTimeout(resolve, 100)); }
    throw new Error(`Did not render: ${condition}\n${await evaluate('document.body.innerText')}`);
  };
  const fill = async (name, value) => evaluate(`(() => { const input=document.getElementById(${JSON.stringify(name)}); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,${JSON.stringify(value)}); input.dispatchEvent(new Event('input',{bubbles:true})); })()`);
  const click = text => evaluate(`Array.from(document.querySelectorAll('button')).find(button=>button.textContent===${JSON.stringify(text)}).click()`);
  await window.loadURL(origin);
  await wait("document.body.innerText.includes('Sign in to Banger')");
  await click('New to Banger? Create an account');
  await wait("document.body.innerText.includes('Create your account')");
  await fill('account-username', username);
  await fill('account-password', password);
  await evaluate('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');
  await writeFile('/tmp/banger-account-signup.png', (await window.webContents.capturePage()).toPNG());
  await click('Create account');
  await wait("document.body.innerText.includes('Start making music')");
  assert.equal(await evaluate('document.cookie.includes("banger_session")'), false);
  assert.equal(await evaluate(`document.body.innerText.includes(${JSON.stringify(username)})`), true);
  await window.reload();
  await wait("document.body.innerText.includes('Start making music')");
  await evaluate('void(window.confirm=()=>true)');
  await click('Sign out');
  await wait("document.body.innerText.includes('Sign in to Banger')");
  await fill('account-username', username.toUpperCase());
  await fill('account-password', 'incorrect-password');
  await click('Sign in');
  await wait("document.body.innerText.includes('Incorrect username or password')");
  await fill('account-password', password);
  await click('Sign in');
  await wait("document.body.innerText.includes('Start making music')");
  await writeFile('/tmp/banger-account-signed-in.png', (await window.webContents.capturePage()).toPNG());
  if (process.argv.includes('--projects')) {
    const fixture = 'tempo 124; meter 4/4; track kick { sound "drums/kick"; rhythm "x . x ."; gain .6; }';
    window.webContents.session.on('will-download', (_event, item) => { item.setSavePath(`/tmp/banger-web-smoke-${username}.wav`); });
    await click('Load Sample Project');
    await wait("Boolean(document.querySelector('.web-project-picker[open]'))");
    await evaluate(`(() => { const input=document.querySelector('.web-project-picker input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,${JSON.stringify(username + ' Project')}); input.dispatchEvent(new Event('input',{bubbles:true})); })()`);
    await evaluate("document.querySelector('.web-project-picker button[type=submit]').click()");
    await wait("Boolean(document.querySelector('#studio-tab-source'))");
    await evaluate("document.querySelector('#studio-tab-source').click()");
    await evaluate(`(() => { const input=document.querySelector('#producer-source'); Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(input,${JSON.stringify(fixture)}); input.dispatchEvent(new Event('input',{bubbles:true})); })()`);
    await click('Apply source');
    await click('Project');
    await wait("Boolean(document.querySelector('#project-controls[open]'))");
    await evaluate("[...document.querySelectorAll('#project-controls button')].find(button=>button.textContent.includes('Save .banger')).click()");
    await wait("document.querySelector('.project-file-identity').innerText.includes('Saved')");
    assert.equal(await evaluate("getComputedStyle(document.querySelector('.project-cloud-controls')).display"), 'none');
    await evaluate("document.querySelector('[aria-label=\"Close project controls\"]').click()");
    assert.equal(await evaluate("window.bangerWorkspace.read('night-drive.banger').then(file=>file.source)"), fixture);
    const draft = await evaluate(`(async()=>{const token=await window.bangerStorage.prepare('night-drive.banger');await window.bangerStorage.saveDraft(token,{schemaVersion:1,lyrics:'Saved project lyrics'},null);return window.bangerStorage.readDraft(token);})()`);
    assert.equal(draft.lyrics, 'Saved project lyrics');
    await evaluate("document.querySelector('.studio-header-export button').click()");
    await wait("Boolean(document.querySelector('.studio-header-export [role=menuitem]'))");
    await evaluate("[...document.querySelectorAll('.studio-header-export [role=menuitem]')].find(button=>button.textContent==='Export and save to library').click()");
    await wait("document.querySelector('.studio-header-export-status').textContent.includes('Exported and saved to library')");
    await window.reload();
    await wait("document.body.innerText.includes('Start making music')");
    await click('Open Project');
    await wait("Boolean(document.querySelector('.web-project-picker[open]'))");
    await evaluate("document.querySelector('.web-project-picker button[type=submit]').click()");
    await wait("Boolean(document.querySelector('#studio-tab-source'))");
    assert.equal(await evaluate("document.querySelector('#producer-source').value"), fixture);
    assert.equal(await evaluate("(async()=>{const token=await window.bangerStorage.prepare('night-drive.banger');return (await window.bangerStorage.readDraft(token)).lyrics;})()"), 'Saved project lyrics');
    await evaluate("(() => { const select=document.querySelector('[aria-label=View]');select.value='library';select.dispatchEvent(new Event('change',{bubbles:true})); })()");
    await wait("Boolean(document.querySelector('.library-card'))");
    await evaluate("document.querySelector('.library-card').click()");
    await wait("[...document.querySelectorAll('audio')].some(audio=>!audio.paused && audio.currentTime>0)");
    const rendered = await evaluate("(async()=>{const songs=await window.bangerLibrary.list();const saved=await window.bangerLibrary.read(songs[0].id);const context=new AudioContext();try{const audio=await context.decodeAudioData(new Uint8Array(saved.bytes).buffer);const samples=audio.getChannelData(0);return {seconds:audio.duration,finite:samples.every(Number.isFinite),peak:samples.reduce((value,sample)=>Math.max(value,Math.abs(sample)),0)};}finally{await context.close();}})()");
    assert.equal(rendered.finite, true);assert.ok(rendered.peak>0.01);assert.ok(rendered.seconds>1);
    await evaluate('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');
    await writeFile('/tmp/banger-web-library.png', (await window.webContents.capturePage()).toPNG());
    console.log('PASS: account project creation, source save/reopen, durable drafts, WAV render/archive/download, persisted library, decoded non-silent audio and playback');
  }
  assert.deepEqual(errors, []);
  console.log('PASS: rendered signup, private cookie, reload, logout, invalid password, case-insensitive returning sign-in');
  window.destroy(); clearTimeout(timer); app.exit(0);
}).catch(error => { console.error(error); clearTimeout(timer); app.exit(1); });
