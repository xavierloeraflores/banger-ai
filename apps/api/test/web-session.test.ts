import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { authenticate } from '../src/server/auth';
import { db } from '../src/server/db';
import { accountInput, hashPassword, verifyPassword, sessionCookie, sessionUser, signIn, signOut } from '../src/server/web-session';

const origin = 'https://studio.example.test';
const request = (cookie?: string, method = 'POST') => new Request(`${origin}/api/session`, { method, headers: { Origin: origin, ...(cookie ? { Cookie: cookie.split(';')[0]! } : {}) } });
test('account credentials are bounded, normalized and salted', async () => {
  assert.deepEqual(accountInput('  Music_Fan  ', 'a long password'), { username: 'music_fan', password: 'a long password' });
  for (const name of ['ab', '../user', 'x'.repeat(33), '', 'a b']) assert.throws(() => accountInput(name, 'a long password'));
  for (const password of ['short', 'a'.repeat(129), null]) assert.throws(() => accountInput('user', password));
  const first = await hashPassword('a long password');
  const second = await hashPassword('a long password');
  assert.notEqual(first, second);
  assert.equal(await verifyPassword('a long password', first), true);
  assert.equal(await verifyPassword('incorrect password', first), false);
  assert.equal(await verifyPassword('a long password'), false);
  assert.ok(!first.includes('a long password'));
});
test('cookies are private and cross-origin authentication is rejected', async () => {
  process.env.APP_ORIGIN = origin;
  const cookie = sessionCookie(request(), 'a'.repeat(64));
  assert.match(cookie, /HttpOnly/); assert.match(cookie, /Secure/); assert.match(cookie, /SameSite=Strict/);
  assert.match(sessionCookie(request(), ''), /Max-Age=0/);
  await assert.rejects(signIn(new Request(`${origin}/api/session`, { method: 'POST', headers: { Origin: 'https://attacker.example.test' } }), 'user', 'a long password'), /Banger app/);
  await assert.rejects(sessionUser(request('banger_session=forged')), /Sign in/);
});
test('accounts isolate workspaces, revoke sessions, expire and throttle guesses', { skip: !process.env.DATABASE_URL }, async t => {
  process.env.APP_ORIGIN = origin;
  t.after(() => db().end());
  const username = `u_${randomUUID().replaceAll('-', '').slice(0, 24)}`;
  const password = 'unique test account password';
  const cookie = await signIn(request(), username, password, true);
  const user = await sessionUser(request(cookie));
  assert.match(user, /^web:/);
  assert.equal(await authenticate(request(cookie, 'GET')), user);
  await assert.rejects(signIn(request(), username.toUpperCase(), password, true), /unavailable/);
  await assert.rejects(signIn(request(), username, 'incorrect password'), /Incorrect username or password/);
  const next = await signIn(request(cookie), username.toUpperCase(), password);
  await assert.rejects(sessionUser(request(cookie)), /expired/);
  assert.equal(await sessionUser(request(next)), user);
  await assert.rejects(authenticate(new Request(`${origin}/api/projects`, { method: 'POST', headers: { Cookie: next, Origin: 'https://attacker.example.test' } })), /Banger app/);
  const other = await signIn(request(), `${username}b`, password, true);
  assert.notEqual(await sessionUser(request(other)), user);
  await signOut(request(next));
  await assert.rejects(sessionUser(request(next)), /expired/);
  const expiring = await signIn(request(), username, password);
  await db().query('UPDATE web_sessions SET expires_at=now()-interval \'1 second\' WHERE user_id=$1', [user]);
  await assert.rejects(sessionUser(request(expiring)), /expired/);
  for (let i = 0; i < 5; i++) await assert.rejects(signIn(request(), username, 'incorrect password'), /Incorrect|Too many/);
  await assert.rejects(signIn(request(), username, password), /Too many/);
});
