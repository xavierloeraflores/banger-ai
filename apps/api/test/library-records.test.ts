import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {db} from '../src/server/db';
import {createProject,setMember} from '../src/server/projects';
import {saveLibraryEntry,readLibraryEntry,generateLibraryArtwork} from '../src/server/library';
const enabled=Boolean(process.env.DATABASE_URL);
test('library records group a project, isolate accounts, and lease one asynchronous cover',{skip:!enabled},async()=>{
 const user=`records-${randomUUID()}`, other=`records-${randomUUID()}`;
 const project=await createProject(user,'Test record',[]);
 await db().query('UPDATE projects SET original_prompt=$2 WHERE id=$1',[project.projectId,'Moonlit jazz']);
 const artifact=randomUUID();
 await db().query("INSERT INTO artifacts(id,project_id,revision,user_id,kind,pathname,content_type,status) VALUES($1,$2,0,$3,'wav',$4,'audio/wav','ready')",[artifact,project.projectId,user,`fixture/${artifact}.wav`]);
 const entries=await Promise.all(['One','Two'].map(name=>saveLibraryEntry(user,{name,artifactId:artifact,beat:{name:`${name}.banger`,source:'tempo 90;'}})));
 assert.equal(entries[0].recordId,entries[1].recordId);assert.equal(entries[0].recordId.length,36);
 await setMember(user,project.projectId,other,'viewer');
 const separate=await saveLibraryEntry(other,{name:'One',artifactId:artifact});assert.notEqual(separate.recordId,entries[0].recordId);
 await assert.rejects(readLibraryEntry(other,entries[0].id),/not found/);
 let calls=0,finish!:()=>void;const gate=new Promise<void>(resolve=>{finish=resolve;});
 const generate=async(context:{prompt?:string})=>{calls++;assert.equal(context.prompt,'Moonlit jazz');await gate;return 'data:image/png;base64,aW1hZ2U=';};
 const first=generateLibraryArtwork(user,entries[0].recordId,{provider:'meta',key:'fixture'},generate);
 for(let i=0;i<100 && calls===0;i++)await new Promise(resolve=>setTimeout(resolve,10));
 await generateLibraryArtwork(user,entries[0].recordId,{provider:'meta',key:'fixture'},generate);
 await generateLibraryArtwork(other,entries[0].recordId,{provider:'meta',key:'fixture'},generate);
 assert.equal(calls,1);assert.equal((await readLibraryEntry(user,entries[0].id)).artifactId,artifact);
 finish();await first;
 await generateLibraryArtwork(user,entries[0].recordId,{provider:'meta',key:'fixture'},generate);assert.equal(calls,1);
 const rows=(await db().query('SELECT r.artwork FROM library_entries l JOIN library_records r ON r.id=l.record_id WHERE l.user_id=$1',[user])).rows;
 assert.equal(rows.length,2);assert.ok(rows.every(row=>row.artwork==='data:image/png;base64,aW1hZ2U='));
 const fail=async()=>{throw new Error('secret provider error');};
 for(let i=0;i<5;i++)await generateLibraryArtwork(other,separate.recordId,{provider:'meta',key:'fixture'},fail);
 assert.equal((await db().query('SELECT attempts FROM library_records WHERE id=$1',[separate.recordId])).rows[0].attempts,3);
});
after(async()=>{await db().end();});
